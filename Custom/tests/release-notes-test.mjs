import assert from "node:assert/strict";
import { previousReleaseDetails, renderReleaseNotes, upstreamSummary } from "../release-notes.mjs";
const sha = "a".repeat(40), old = "b".repeat(40);
const metadata = { version: "0.1.0", upstream_tag: "v0.11.12", upstream_commit: "c".repeat(40), repository: "owner/launcher" };
const upstream = { tagName: metadata.upstream_tag, url: `https://github.com/abue-ammar/tinycast/releases/tag/${metadata.upstream_tag}`,
  body: "## Fixed\r\n* Fix clipboard ordering in #123\r\n\r\n<!-- tinycast:install -->\n\nbrew install tinycast\nxattr -dr /Applications/Tinycast.app", isDraft: false, isPrerelease: false };
const initial = renderReleaseNotes({ metadata, commit: sha, upstream });
assert.match(initial, /first ZLaunch release/);
assert.ok(!initial.includes("<!--"), "Native release-note UI must not display metadata comments.");
assert.match(initial, /Extension cleanup stays unavailable/);
assert.ok(initial.includes("[#123](https://github.com/abue-ammar/tinycast/issues/123)"));
assert.ok(initial.includes(`https://github.com/owner/launcher/tree/${sha}`));
assert.ok(initial.includes(`https://github.com/abue-ammar/tinycast/tree/${metadata.upstream_commit}`));
assert.ok(!initial.includes("brew install") && !initial.includes("xattr") && !initial.includes("tinycast:install"));
const previous = previousReleaseDetails({ tagName: "v0.1.0", body: initial });
assert.equal(previous.upstreamTag, metadata.upstream_tag);
assert.equal(previous.sourceCommit, sha);
const patch = renderReleaseNotes({ metadata: { ...metadata, version: "0.1.1" }, commit: old, upstream, previous, changes: ["Fix update notification wording"] });
assert.match(patch, /base is unchanged from ZLaunch 0\.1\.0/);
assert.match(patch, /not new fixes introduced by this ZLaunch update/);
assert.match(patch, /Fix update notification wording/);
assert.ok(!patch.includes("first ZLaunch release") && !patch.includes("updates the Tinycast base"));
const unknown = renderReleaseNotes({ metadata, commit: sha, upstream, previous: { tag: "v0.0.8" } });
assert.ok(!unknown.includes("updates the Tinycast base"));
const advanced = renderReleaseNotes({ metadata, commit: sha, upstream, previous: { tag: "v0.0.9", upstreamTag: "v0.11.11" }, changes: ["Update upstream"] });
assert.match(advanced, /updates the Tinycast base to v0\.11\.12/);
assert.equal(upstreamSummary("A release without a marker"), "A release without a marker");
assert.equal(upstreamSummary("Already [#12](https://github.com/example/issues/12)"), "Already [#12](https://github.com/example/issues/12)");
assert.throws(() => renderReleaseNotes({ metadata, commit: sha, upstream: { ...upstream, tagName: "v0.11.11" } }));
assert.throws(() => renderReleaseNotes({ metadata, commit: sha, upstream: { ...upstream, isDraft: true } }));
assert.throws(() => renderReleaseNotes({ metadata, commit: sha, upstream: { ...upstream, body: "<!-- tinycast:install -->instructions only" } }));
assert.deepEqual(previousReleaseDetails({ tagName: "v0.1.0", body: `ZLaunch 0.1.0, based on Tinycast v0.11.12.\nSource: https://github.com/owner/launcher/tree/${old}` }), { tag: "v0.1.0", upstreamTag: "v0.11.12", sourceCommit: old });
assert.equal(renderReleaseNotes({ metadata, commit: sha, upstream }), initial, "Offline fixture rendering must be deterministic.");
console.log("Release notes cover provenance, complete upstream fixes, installer removal, same-base patches, and offline determinism.");

const betaMetadata = { ...metadata, upstream_tag: "v0.11.14-beta.112", upstream_prerelease: true };
const betaUpstream = { ...upstream, tagName: betaMetadata.upstream_tag, isPrerelease: true,
  url: `https://github.com/abue-ammar/tinycast/releases/tag/${betaMetadata.upstream_tag}` };
const beta = renderReleaseNotes({ metadata: betaMetadata, commit: sha, upstream: betaUpstream, previous });
assert.match(beta, /v0\.11\.14-beta\.112 \(upstream beta\)/);
assert.equal(previousReleaseDetails({ tagName: "v0.1.6", body: beta }).upstreamTag, betaMetadata.upstream_tag);
assert.throws(() => renderReleaseNotes({ metadata: { ...betaMetadata, upstream_prerelease: false }, commit: sha, upstream: betaUpstream }));
assert.throws(() => renderReleaseNotes({ metadata: betaMetadata, commit: sha, upstream: { ...betaUpstream, isPrerelease: false } }));
assert.throws(() => renderReleaseNotes({ metadata: { ...metadata, upstream_prerelease: true }, commit: sha, upstream }));
console.log("Explicit beta provenance is preserved; unapproved or mismatched upstream channels are rejected.");
