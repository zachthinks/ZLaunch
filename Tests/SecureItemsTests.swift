import AppKit
import Foundation

@main
struct SecureItemsTests {
    @MainActor static func main() throws {
        let item = SecureItem(name: "Cloud 🔑", value: "  token\n第二行  ")
        let data = try JSONEncoder().encode([item])
        let decoded = try JSONDecoder().decode([SecureItem].self, from: data)
        precondition(decoded == [item])
        precondition(item.isValid)
        precondition(!SecureItem(name: " \n", value: "key").isValid)
        precondition(!SecureItem(name: "name", value: "").isValid)
        precondition(SecureItem(name: "name", value: " ").isValid)
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let clipboard = SecureItemsClipboard(pasteboard: board)
        clipboard.copy(item.value)
        precondition(board.string(forType: .string) == item.value)
        precondition(board.types?.contains(.init("org.nspasteboard.ConcealedType")) == true)
        precondition(board.types?.contains(.init("org.nspasteboard.AutoGeneratedType")) == true)
        clipboard.clearIfOwned()
        precondition(board.string(forType: .string) == nil)
        clipboard.copy("secret")
        board.clearContents()
        board.setString("new user copy", forType: .string)
        clipboard.clearIfOwned()
        precondition(board.string(forType: .string) == "new user copy")
        print("SecureItemsTests passed")
    }
}
