import AppKit

@MainActor
final class SecureItemsClipboard {
    private let pasteboard: NSPasteboard
    private var changeCount: Int?
    private var clearing: Task<Void, Never>?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    func copy(_ value: String) {
        clearing?.cancel()
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(value, forType: .string)
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
                     "org.nspasteboard.TransientType"] {
            item.setData(Data(), forType: .init(type))
        }
        pasteboard.writeObjects([item])
        changeCount = pasteboard.changeCount
        clearing = Task { [weak self] in
            do { try await Task.sleep(for: .seconds(30)) } catch { return }
            self?.clearIfOwned()
        }
    }

    func clearIfOwned() {
        clearing?.cancel()
        clearing = nil
        if let changeCount, pasteboard.changeCount == changeCount { pasteboard.clearContents() }
        changeCount = nil
    }

    isolated deinit { clearing?.cancel() }
}
